// 날짜마다 정해진 한 문장 (폰과 태블릿에서 같은 날엔 같은 문장)
export function quoteIndexFor(date) {
  const n = diffDays('2026-01-01', date);
  return ((n % QUOTES.length) + QUOTES.length) % QUOTES.length;
}
